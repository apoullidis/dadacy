const HYPHEN = 'U+002D "-" in the template text';

/** Plants `value` as <locale>/<file>'s <key> and returns the run plus the R1 lines it raised. */
function withHyphen(
  locale: string,
  file: string,
  key: string,
  value: string,
): { run: GateRun; r1: string[] } {
  const root = freshRoot();
  const path = join(root, 'catalogues', locale, file);
  plantJson(path, (d) => {
    d[key] = value;
  });
  assert.equal(readDoc(path)[key], value);
  const run = runGate(root);
  return { run, r1: run.problems.filter((p) => p.startsWith('UNSPEAKABLE-CHAR')) };
}

